import { Database, FlaskConical, History } from 'lucide-react'
import { useCallback, useEffect, useState } from 'react'
import { api } from '../api/client'
import { Alert, Button, Card, PageHeader, Pill, Spinner, Stat, formatDateTime } from '../components/ui'

const originTone = { collected: 'ok', imported: 'brand', synthetic: 'warn' }

function DatasetCard({ ds, onChanged }) {
  const [versions, setVersions] = useState(null)
  const [busy, setBusy] = useState(false)
  const [msg, setMsg] = useState(null)

  const loadVersions = useCallback(() => {
    api.dataset(ds.datasetId).then((r) => setVersions(r.data.versions)).catch((e) => setMsg({ tone: 'rec', text: e.message }))
  }, [ds.datasetId])
  useEffect(loadVersions, [loadVersions])

  const snapshot = async () => {
    setBusy(true)
    setMsg(null)
    try {
      const res = await api.createDatasetVersion(ds.datasetId, '')
      setMsg(
        res.meta.created
          ? { tone: 'ok', text: `Created version ${res.data.version} (${res.data.sessionCount} completed sessions).` }
          : { tone: 'info', text: `No changes since version ${res.data.version}; no new version created.` },
      )
      loadVersions()
      onChanged()
    } catch (e) {
      setMsg({ tone: 'rec', text: e.message })
    } finally {
      setBusy(false)
    }
  }

  return (
    <Card>
      <div className="flex flex-wrap items-start justify-between gap-3">
        <div>
          <div className="flex flex-wrap items-center gap-2">
            <h2 className="font-mono text-base font-semibold">{ds.datasetId}</h2>
            <Pill tone={originTone[ds.dataOrigin]}>{ds.dataOrigin}</Pill>
          </div>
          <p className="mt-1 text-sm text-muted">
            {formatDateTime(ds.coverageStart)} → {formatDateTime(ds.coverageEnd)}
          </p>
        </div>
        <Button variant="secondary" size="sm" onClick={snapshot} loading={busy}>
          <History className="size-4" aria-hidden /> Freeze new version
        </Button>
      </div>

      {ds.dataOrigin === 'synthetic' && (
        <div className="mt-4">
          <Alert tone="warn" icon={FlaskConical} title="Synthetic development data">
            Generated by the seed script around fictional places. Never report results from this dataset as NIT Raipur observations.
          </Alert>
        </div>
      )}

      <div className="mt-5 grid grid-cols-2 gap-4 sm:grid-cols-4">
        <Stat label="Sessions" value={ds.sessionCount} />
        <Stat label="Participants" value={ds.participantCount} hint="distinct contributors" />
        <Stat label="Accepted obs." value={ds.observationCount.toLocaleString()} />
        <Stat label="Rejected obs." value={ds.rejectedCount.toLocaleString()} hint="failed validation" />
      </div>

      {msg && <div className="mt-4"><Alert tone={msg.tone} title={msg.text} /></div>}

      <div className="mt-5 border-t border-line pt-4">
        <h3 className="text-sm font-semibold">Frozen versions</h3>
        {!versions ? (
          <Spinner />
        ) : versions.length === 0 ? (
          <p className="mt-2 text-sm text-muted">None yet. Freeze a version before running analyses so results are reproducible.</p>
        ) : (
          <div className="mt-2 overflow-x-auto">
            <table className="w-full min-w-[34rem] text-left text-sm">
              <thead className="text-xs uppercase tracking-wide text-muted">
                <tr><th className="py-2 pr-3 font-medium">Version</th><th className="pr-3 font-medium">Created</th><th className="pr-3 font-medium">Sessions</th><th className="pr-3 font-medium">Obs.</th><th className="pr-3 font-medium">Hash</th><th className="font-medium">State</th></tr>
              </thead>
              <tbody className="tabular divide-y divide-line">
                {versions.map((v) => (
                  <tr key={v.version}>
                    <td className="py-2 pr-3 font-mono">v{v.version}</td>
                    <td className="pr-3">{formatDateTime(v.createdAt)}</td>
                    <td className="pr-3">{v.sessionCount}</td>
                    <td className="pr-3">{v.observationCount.toLocaleString()}</td>
                    <td className="pr-3 font-mono text-xs text-muted" title={v.contentHash}>{v.contentHash.slice(0, 10)}…</td>
                    <td>{v.invalidatedAt ? <Pill tone="rec" >invalidated · {v.invalidationReason.replaceAll('_', ' ')}</Pill> : <Pill tone="ok">valid</Pill>}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </div>
    </Card>
  )
}

export default function Research() {
  const [datasets, setDatasets] = useState(null)
  const [error, setError] = useState(null)
  const load = useCallback(() => {
    api.datasets().then((r) => setDatasets(r.data)).catch((e) => setError(e.message))
  }, [])
  useEffect(load, [load])

  return (
    <div className="space-y-6">
      <PageHeader eyebrow="Research workspace" title="Datasets">
        Aggregate dataset summaries and frozen versions. Raw individual traces are not available here. Analytics (cleaning, stay points,
        routes, sequences, clusters) are added in later phases and will run against frozen versions only.
      </PageHeader>
      {error && <Alert tone="rec" title="Could not load datasets">{error}</Alert>}
      {!datasets && !error && <Spinner />}
      {datasets?.length === 0 && (
        <Card className="flex items-center gap-3 text-muted"><Database className="size-5" aria-hidden />No data has been collected yet.</Card>
      )}
      {datasets?.map((ds) => <DatasetCard key={ds.datasetId} ds={ds} onChanged={load} />)}
    </div>
  )
}
